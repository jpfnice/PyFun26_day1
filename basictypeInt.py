# The "basic" type int

nb=123 # an int represent in base 10 (decimal representation)
print(nb,type(nb))

nb=0b1001 # an int represented is base 2 (binary)
print(nb)

nb=0o4321 # an int represented in base 8 (octal)
print(nb)

nb=0xFFA9 # an int represented in base 16 (hexadecimal)
print(nb)

nb=int()
print(nb)

nb=int(45.78)
print(nb)

nb=int("456")
print(nb)

